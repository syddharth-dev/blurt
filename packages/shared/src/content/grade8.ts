/**
 * Words to bias the recognizer with (`contextualStrings`): every term plus its
 * variants and confusables, so "mitochondria" isn't heard as "mighty Kandria".
 */
export function recognizerHints(terms: readonly ContentTerm[]): string[] {
  const words = terms.flatMap((t) => [
    t.canonical,
    ...t.accept,
    ...t.close.map((c) => c.text),
    ...t.confusables.map((c) => c.text),
  ]);
  return [...new Set(words)];
}
